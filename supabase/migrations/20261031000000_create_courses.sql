create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  code text not null,
  title text not null,
  credits integer not null check (credits > 0),
  status text not null default 'planned'
    check (status in ('planned', 'active', 'done')),
  created_at timestamptz not null default now()
);

alter table public.courses enable row level security;

grant select, insert, update, delete on public.courses to anon, authenticated;
grant usage, select on sequence public.courses_id_seq to anon, authenticated;

-- Lab-only policy: the worksheet uses an anonymous client without auth.
-- Replace these policies with ownership-based policies before production use.
drop policy if exists "lab courses select" on public.courses;
drop policy if exists "lab courses insert" on public.courses;
drop policy if exists "lab courses update" on public.courses;
drop policy if exists "lab courses delete" on public.courses;

create policy "lab courses select"
  on public.courses for select
  to anon, authenticated
  using (true);

create policy "lab courses insert"
  on public.courses for insert
  to anon, authenticated
  with check (true);

create policy "lab courses update"
  on public.courses for update
  to anon, authenticated
  using (true)
  with check (true);

create policy "lab courses delete"
  on public.courses for delete
  to anon, authenticated
  using (true);

insert into public.courses (code, title, credits, status)
select seed.code, seed.title, seed.credits, seed.status
from (
  values
    ('MOB01', 'Mobile Programming', 3, 'active'),
    ('WEB02', 'Web Service Integration', 3, 'planned'),
    ('DB03', 'Database Fundamentals', 2, 'done')
) as seed(code, title, credits, status)
where not exists (
  select 1 from public.courses existing where existing.code = seed.code
);
